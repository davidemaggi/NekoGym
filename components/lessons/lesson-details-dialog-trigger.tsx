/** A person in the lesson; staff views carry their plan usage for the lesson's period. */
export type LessonPerson = {
  id: string;
  name: string;
  email?: string;
  planUsage?: PlanUsage;
  /** Pending requests only: why the medical certificate made the booking wait for approval. */
  approvalNote?: string | null;
};

type LessonDetailsDialogTriggerProps = {
  locale: string;
  trigger: ReactNode;
  /** Second trigger beside the first, opening the people manager directly ("Gestisci persone"). */
  peopleTrigger?: ReactNode;
  /** The (only) trigger opens the people manager instead of the lesson dialog (e.g. "Presenze"). */
  openPeopleDirectly?: boolean;
  footerSlot?: ReactNode;
  labels: {
    detailsTitle: string;
    detailsDescription: string;
    startsAtLabel: string;
    endsAtLabel: string;
    trainerLabel: string;
    bookedLabel: string;
    queuedLabel: string;
    closeCta: string;
    courseTag: string;
    lessonDescriptionLabel: string;
    notifySectionTitle: string;
    notifyMessagePlaceholder: string;
    notifySendCta: string;
  };
  lesson: {
    id: string;
    title: string;
    description: string | null;
    startsAt: string;
    endsAt: string;
    trainerName: string | null;
    occupancy: string;
    queueLength: number;
    canViewWaitlist: boolean;
    isCourseLesson: boolean;
    courseId?: string | null;
    courseName?: string;
    /** Markdown; shown under the lesson's own notes for lessons generated by a course. */
    courseDescription?: string | null;
    lessonTypeName: string | null;
    lessonTypeIcon: string | null;
    lessonTypeColor: string | null;
    canBroadcast: boolean;
  };
  manage?: {
    lesson: {
      id: string;
      canEditMain: boolean;
      title: string;
      description: string;
      startsAt: string;
      durationMinutes: number;
      maxAttendees: number;
      cancellationWindowHours: number;
      trainerId: string;
      lessonTypeId: string;
      canManageTrainer: boolean;
      canManageAttendance: boolean;
      attendees: Array<LessonPerson>;
      attendeeAttendance: Record<string, "PRESENT" | "NO_SHOW" | null>;
      pendingApprovals: Array<LessonPerson>;
      waitlist: Array<LessonPerson>;
    };
    trainerCandidates: Array<{ id: string; name: string }>;
    lessonTypeCandidates: Array<{ id: string; name: string }>;
    attendeeCandidates: Array<{ id: string; name: string; email?: string }>;
    labels: {
      title: string;
      description: string;
      tabMain: string;
      tabPeople: string;
      startsAtLabel: string;
      trainerLabel: string;
      standaloneDuration: string;
      standaloneMaxAttendees: string;
      standaloneCancellationWindow: string;
      standaloneLessonType: string;
      lessonTitleLabel: string;
      lessonDescriptionLabel: string;
      updateStandaloneCta: string;
      updateTrainerCta: string;
      attendeesLabel: string;
      noAttendees: string;
      attendeeSelectLabel: string;
      addAttendeeCta: string;
      removeAttendeeCta: string;
      markAttendancePresentCta: string;
      markAttendanceNoShowCta: string;
      attendanceStatusLabel: string;
      attendanceStatusPresent: string;
      attendanceStatusNoShow: string;
      attendanceStatusUnmarked: string;
      pendingApprovalsLabel: string;
      noPendingApprovals: string;
      confirmPendingCta: string;
      confirmPendingAndGrantAccessCta: string;
      rejectPendingCta: string;
      waitlistLabel: string;
      noWaitlist: string;
      confirmWaitlistCta: string;
      removeWaitlistCta: string;
      processing: string;
      closeCta: string;
      manageTriggerLabel: string;
      editLessonCta: string;
      editLessonDescription: string;
      managePeopleCta: string;
      managePeopleDescription: string;
      notifySectionTitle: string;
      notifyMessageLabel: string;
      notifyMessagePlaceholder: string;
      notifySendCta: string;
    };
    canBroadcastToAttendees?: boolean;
    canGrantOpenAccess?: boolean;
  };
};

// Always in the gym's time zone, like every list that opens this dialog.
function formatDay(value: string, locale: string): string {
  return new Intl.DateTimeFormat(locale === "it" ? "it-IT" : "en-GB", {
    weekday: "short",
    day: "numeric",
    month: "short",
    timeZone: getAppDateTimeConfig().timeZone,
  }).format(new Date(value));
}

function formatTime(value: string, locale: string): string {
  return new Intl.DateTimeFormat(locale === "it" ? "it-IT" : "en-GB", {
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
    timeZone: getAppDateTimeConfig().timeZone,
  }).format(new Date(value));
}

export function LessonDetailsDialogTrigger({
  locale,
  trigger,
  peopleTrigger,
  openPeopleDirectly = false,
  footerSlot,
  labels,
  lesson,
  manage,
}: LessonDetailsDialogTriggerProps) {
  const [open, setOpen] = useState(false);
  // Which manager is open: the lesson's own data, or its people.
  const [manageView, setManageView] = useState<"main" | "people" | null>(null);
  const [repeatOpen, setRepeatOpen] = useState(false);
  // Only standalone lessons repeat: a course already owns its schedule.
  const canRepeat = Boolean(manage) && !lesson.isCourseLesson;
  const [detailsTab, setDetailsTab] = useState<"info" | "people">("info");
  const [message, setMessage] = useState("");
  const [isPending, startTransition] = useTransition();
  const peopleCount = manage
    ? manage.lesson.attendees.length + manage.lesson.pendingApprovals.length + manage.lesson.waitlist.length
    : 0;

  function closeDialog() {
    setOpen(false);
    setDetailsTab("info");
    setMessage("");
  }

  function sendNotification() {
    if (!lesson.canBroadcast || !message.trim()) return;
    const formData = new FormData();
    formData.set("locale", locale);
    formData.set("lessonId", lesson.id);
    formData.set("message", message.trim());

    startTransition(async () => {
      const result = await broadcastLessonNotificationMutationAction(formData);
      if (result.ok) {
        toast.success(result.message);
        setMessage("");
      } else {
        toast.error(result.message);
      }
    });
  }

  const timeRange = `${formatDay(lesson.startsAt, locale)} · ${formatTime(lesson.startsAt, locale)}–${formatTime(lesson.endsAt, locale)}`;

  const infoPanel = (
    <div className="space-y-5">
      <dl className="grid grid-cols-[minmax(0,7rem)_minmax(0,1fr)] gap-x-4 gap-y-3 text-[15px]">
        <dt className="text-[var(--muted-foreground)]">{labels.startsAtLabel}</dt>
        <dd className="tabular font-semibold first-letter:uppercase">{timeRange}</dd>
        <dt className="text-[var(--muted-foreground)]">{labels.trainerLabel}</dt>
        <dd className={lesson.trainerName ? undefined : "text-[var(--muted-foreground)]"}>
          {lesson.trainerName ?? (locale === "it" ? "Senza trainer" : "No trainer")}
        </dd>
        {lesson.isCourseLesson && lesson.courseName ? (
          <>
            <dt className="text-[var(--muted-foreground)]">{labels.courseTag}</dt>
            <dd className="flex items-center gap-1.5 font-semibold">
              <BookOpen size={16} aria-hidden="true" className="shrink-0 text-[var(--muted-foreground)]" />
              {lesson.courseName}
            </dd>
          </>
        ) : null}
        <dt className="text-[var(--muted-foreground)]">{labels.bookedLabel}</dt>
        <dd className="tabular">
          {lesson.occupancy}
          {lesson.canViewWaitlist && lesson.queueLength > 0 ? ` · ${labels.queuedLabel} ${lesson.queueLength}` : ""}
        </dd>
      </dl>
      {lesson.description ? (
        <p className="max-w-[60ch] text-[15px] text-[var(--muted-foreground)]">{lesson.description}</p>
      ) : null}
      {lesson.isCourseLesson && (lesson.courseDescription || lesson.courseId) ? (
        <section className="border-t border-[var(--rule)] pt-4">
          {lesson.courseDescription ? <MarkdownView markdown={lesson.courseDescription} /> : null}
          {lesson.courseId ? (
            <Link
              href={`/${locale}/courses/${lesson.courseId}`}
              className="mt-2 inline-flex min-h-11 items-center gap-1 text-[15px] font-semibold underline decoration-[1.5px] underline-offset-4 hover:decoration-2"
            >
              {locale === "it" ? "Scheda del corso" : "Course page"}
              <ChevronRight size={16} aria-hidden="true" />
            </Link>
          ) : null}
        </section>
      ) : null}
      {lesson.canBroadcast ? (
        <div className="space-y-2 border-t border-[var(--rule)] pt-4">
          <p className="text-[15px] font-semibold">{labels.notifySectionTitle}</p>
          <Textarea
            value={message}
            onChange={(event) => setMessage(event.target.value)}
            rows={3}
            placeholder={labels.notifyMessagePlaceholder}
            disabled={isPending}
          />
          <Button type="button" variant="outline" onClick={sendNotification} disabled={isPending || !message.trim()}>
            <Send size={16} aria-hidden="true" />
            {labels.notifySendCta}
          </Button>
        </div>
      ) : null}
    </div>
  );

  function peopleList(title: string, empty: string, people: Array<LessonPerson>, prefix: string) {
    return (
      <section>
        <h3 className="flex items-baseline justify-between text-[15px] font-semibold">
          {title}
          <span className="tabular text-sm font-medium text-[var(--muted-foreground)]">{people.length}</span>
        </h3>
        {people.length === 0 ? (
          <p className="mt-1 text-[15px] text-[var(--muted-foreground)]">{empty}</p>
        ) : (
          <ul className="mt-1 divide-y divide-[var(--rule)]">
            {people.map((person) => (
              <li
                key={`${prefix}-${lesson.id}-${person.id}`}
                className={cn("flex min-h-11 flex-wrap items-center justify-between gap-x-3 text-[15px]", prefix === "pending" && manage ? "gap-y-1 py-2" : "")}
              >
                <UserQuickProfileTooltip userId={person.id} locale={locale}>
                  {person.name}
                </UserQuickProfileTooltip>
                {/* Plan spent in this lesson's week/month: decides approvals and queue promotions at a glance. */}
                {person.planUsage ? <PlanUsageTag usage={person.planUsage} locale={locale} /> : null}
                {prefix === "pending" && person.approvalNote ? (
                  <span className="basis-full text-sm font-semibold text-[var(--warning-fg)]">{person.approvalNote}</span>
                ) : null}
                {prefix === "pending" && manage ? (
                  <PendingApprovalActions
                    locale={locale}
                    lessonId={manage.lesson.id}
                    traineeId={person.id}
                    traineeName={person.name}
                    labels={{ confirm: manage.labels.confirmPendingCta, reject: manage.labels.rejectPendingCta }}
                    className="basis-full"
                  />
                ) : null}
              </li>
            ))}
          </ul>
        )}
      </section>
    );
  }

  return (
    <>
      {peopleTrigger && manage ? (
        <div className="flex flex-wrap items-center gap-2">
          <button type="button" onClick={() => setOpen(true)} className="cursor-pointer text-left">
            {trigger}
          </button>
          <button type="button" onClick={() => setManageView("people")} className="cursor-pointer text-left">
            {peopleTrigger}
          </button>
        </div>
      ) : (
        <button
          type="button"
          onClick={() => (openPeopleDirectly && manage ? setManageView("people") : setOpen(true))}
          className="w-full cursor-pointer text-left"
        >
          {trigger}
        </button>
      )}
      <Dialog open={open} onOpenChange={(next) => (!next ? closeDialog() : setOpen(next))}>
        <DialogContent>
          <DialogHeader>
            <div className="flex items-start gap-3">
              {lesson.lessonTypeIcon ? (
                <span
                  aria-hidden="true"
                  className="inline-flex h-12 w-12 shrink-0 items-center justify-center rounded-xl"
                  style={{
                    backgroundColor: lesson.lessonTypeColor ? hexToRgba(lesson.lessonTypeColor, 0.18) : undefined,
                    border: lesson.lessonTypeColor ? `1px solid ${hexToRgba(lesson.lessonTypeColor, 0.5)}` : undefined,
                  }}
                >
                  <LessonTypeIcon
                    iconPath={lesson.lessonTypeIcon}
                    colorHex={lesson.lessonTypeColor}
                    size={28}
                  />
                </span>
              ) : null}
              <div className="space-y-1">
                <DialogTitle>{lesson.title}</DialogTitle>
                <DialogDescription>
                  {lesson.isCourseLesson ? (
                    // Course lessons say so with an icon, not only a word after the type.
                    <span className="inline-flex flex-wrap items-center gap-x-2 gap-y-1">
                      {lesson.lessonTypeName ? <span>{lesson.lessonTypeName}</span> : null}
                      <span className="inline-flex items-center gap-1 rounded-full bg-[var(--muted)] px-2 py-0.5 text-sm font-semibold text-[var(--foreground)]">
                        <BookOpen size={14} aria-hidden="true" />
                        {labels.courseTag}
                      </span>
                    </span>
                  ) : (
                    lesson.lessonTypeName ?? labels.detailsDescription
                  )}
                </DialogDescription>
              </div>
            </div>
          </DialogHeader>

          {manage ? (
            <Tabs value={detailsTab} onValueChange={(value) => setDetailsTab(value === "people" ? "people" : "info")}>
              <TabsList className="grid w-full grid-cols-2">
                <TabsTrigger value="info">{manage.labels.tabMain}</TabsTrigger>
                <TabsTrigger value="people" title={`${manage.labels.tabPeople} (${peopleCount})`}>
                  <span>{manage.labels.tabPeople}</span>
                  <span className="tabular ml-1 text-sm text-[var(--muted-foreground)]">{peopleCount}</span>
                </TabsTrigger>
              </TabsList>

              <TabsContent value="info">{infoPanel}</TabsContent>

              <TabsContent value="people" className="space-y-5">
                {peopleList(manage.labels.attendeesLabel, manage.labels.noAttendees, manage.lesson.attendees, "attendee")}
                {peopleList(manage.labels.pendingApprovalsLabel, manage.labels.noPendingApprovals, manage.lesson.pendingApprovals, "pending")}
                {peopleList(manage.labels.waitlistLabel, manage.labels.noWaitlist, manage.lesson.waitlist, "waitlist")}
                <Button
                  type="button"
                  variant="outline"
                  onClick={() => {
                    setOpen(false);
                    setManageView("people");
                  }}
                >
                  <Users size={16} aria-hidden="true" />
                  {manage.labels.managePeopleCta}
                </Button>
              </TabsContent>
            </Tabs>
          ) : (
            infoPanel
          )}

          <DialogFooter>
            {footerSlot}
            <Button type="button" variant="ghost" onClick={closeDialog}>
              {labels.closeCta}
            </Button>
            {canRepeat ? (
              <Button
                type="button"
                variant="ghost"
                onClick={() => {
                  setOpen(false);
                  setRepeatOpen(true);
                }}
              >
                <Repeat size={16} aria-hidden="true" />
                {locale === "it" ? "Ripeti…" : "Repeat…"}
              </Button>
            ) : null}
            {/* Course lessons take their data from the course: only their people are managed here. */}
            {manage && manage.lesson.canEditMain ? (
              <Button
                type="button"
                onClick={() => {
                  setOpen(false);
                  setManageView("main");
                }}
              >
                <Pencil size={16} aria-hidden="true" />
                {manage.labels.editLessonCta}
              </Button>
            ) : null}
          </DialogFooter>
        </DialogContent>
      </Dialog>

      {canRepeat ? (
        <RepeatLessonDialog
          locale={locale}
          lesson={{ id: lesson.id, title: lesson.title, startsAt: lesson.startsAt }}
          open={repeatOpen}
          onOpenChange={setRepeatOpen}
        />
      ) : null}

      {manage ? (
        <LessonManageDialog
          open={manageView !== null}
          showDefaultTrigger={false}
          onOpenChangeAction={(next) => !next && setManageView(null)}
          view={manageView ?? "people"}
          viewTitle={manageView === "main" ? manage.labels.editLessonCta : manage.labels.managePeopleCta}
          viewDescription={manageView === "main" ? manage.labels.editLessonDescription : manage.labels.managePeopleDescription}
          locale={locale}
          lesson={manage.lesson}
          trainerCandidates={manage.trainerCandidates}
          lessonTypeCandidates={manage.lessonTypeCandidates}
          attendeeCandidates={manage.attendeeCandidates}
          canBroadcastToAttendees={manage.canBroadcastToAttendees}
          canGrantOpenAccess={manage.canGrantOpenAccess}
          labels={manage.labels}
        />
      ) : null}
    </>
  );
}
